// Run inside the OpenWA container. All test rows and edits are rolled back.
const { createRequire } = require('node:module');
const req = createRequire('/app/package.json');
const assert = require('node:assert/strict');
const { randomUUID, randomBytes, createHash } = require('node:crypto');
const { DataSource } = req('typeorm');
const { OperatorAuthService } = req('/app/dist/modules/operator-auth/operator-auth.service.js');
const { OperatorWriteGuard } = req('/app/dist/modules/operator-auth/operator-write.guard.js');
const { ConversationAssignmentController } = req('/app/dist/modules/session/conversation-assignment.controller.js');

async function main() {
  const db = new DataSource({type:'postgres',host:process.env.DATABASE_HOST,port:Number(process.env.DATABASE_PORT),username:process.env.DATABASE_USERNAME,password:process.env.DATABASE_PASSWORD,database:process.env.DATABASE_NAME});
  await db.initialize();
  // Initialize the real migration before opening the rollback-only test transaction.
  const real = new OperatorAuthService(db);
  await real.onModuleInit();
  await real.me('').catch(()=>{});
  const runner = db.createQueryRunner();
  await runner.startTransaction();
  const adapter = {query:(sql,args)=>runner.query(sql,args),transaction:fn=>fn(adapter)};
  adapter.manager=adapter;
  const service = new OperatorAuthService(adapter);
  let passed=0;
  const ok=label=>{passed++;console.log('PASS '+label);};
  try {
    const suffix=randomUUID().slice(0,8);
    const admin=await service.register('qa_admin_'+suffix,'QA Admin','test-only-password');
    const agent=await service.register('qa_agent_'+suffix,'QA Agent','test-only-password');
    assert.equal(agent.user.role,'agent'); ok('new registration defaults to agent');
    await runner.query("UPDATE openwa.operator_users SET role='admin' WHERE id=$1",[admin.user.id]);
    assert.equal((await service.assignmentTarget(admin.token,agent.user.id)).displayName,'QA Agent');
    await assert.rejects(()=>service.assignmentTarget(admin.token,randomUUID()),e=>e.getStatus()===403);
    ok('transfer resolves the active target profile and rejects invalid accounts');
    const signedIn=await service.login('qa_agent_'+suffix,'test-only-password');
    assert.equal(signedIn.user.id,agent.user.id);
    assert.equal('passwordHash' in signedIn.user,false);ok('login returns safe profile');
    await assert.rejects(()=>service.administration(agent.token),e=>e.getStatus()===403);ok('agent cannot administer');
    const changed=await service.updateUser(admin.token,agent.user.id,{role:'agent',active:true,canSend:false,canAssign:false});
    assert.equal(changed.id,agent.user.id);
    assert.equal(changed.canSend,false);
    await assert.rejects(()=>service.requirePermission(agent.token,'canSend'),e=>e.getStatus()===403);
    await assert.rejects(()=>service.requirePermission(agent.token,'canAssign'),e=>e.getStatus()===403);ok('send and assignment permissions enforced');
    process.env.ATENDE_REQUIRE_OPERATOR='true';
    const guard=new OperatorWriteGuard(service);
    const request={method:'POST',headers:{'x-atende-token':agent.token},body:{}};
    const context={switchToHttp:()=>({getRequest:()=>request}),getClass:()=>({name:'MessageController'})};
    await assert.rejects(()=>guard.canActivate(context),e=>e.getStatus()===403);
    request.headers={};
    await assert.rejects(()=>guard.canActivate(context),e=>e.getStatus()===401);ok('API key without employee token cannot send');
    const session='qa-'+randomUUID(), chat='qa-'+randomUUID()+'@c.us';
    await service.setRecipient(admin.token,agent.user.id);
    assert.equal((await service.notification(agent.token,session,chat)).allowed,true);
    assert.equal((await service.notification(admin.token,session,chat)).allowed,false);
    assert.equal((await service.notification(agent.token,session,'123@g.us')).allowed,false);ok('unassigned recipient only, no groups');
    await runner.query('INSERT INTO openwa.conversation_assignments (session_id,chat_id,assignee_id,assignee_name) VALUES ($1,$2,$3,$4)',[session,chat,admin.user.id,'QA Admin']);
    assert.equal((await service.notification(agent.token,session,chat)).allowed,false);
    assert.equal((await service.notification(admin.token,session,chat)).allowed,true);ok('assigned notification overrides unassigned recipient');
    const assignments=new ConversationAssignmentController(adapter);
    await runner.query("UPDATE openwa.conversation_assignments SET updated_at=NOW()-INTERVAL '1 hour' WHERE session_id=$1 AND chat_id=$2",[session,chat]);
    const before=await assignments.getAssignment(session,chat);
    const same=await assignments.assign(session,chat,{assigneeId:admin.user.id,assigneeName:'QA Admin'});
    assert.equal(new Date(same.updatedAt).valueOf(),new Date(before.updatedAt).valueOf());
    const transferRequest={method:'PUT',headers:{'x-atende-token':admin.token},body:{assigneeId:agent.user.id,assigneeName:'Spoofed'}};
    await guard.canActivate({switchToHttp:()=>({getRequest:()=>transferRequest}),getClass:()=>({name:'ConversationAssignmentController'})});
    assert.equal(transferRequest.body.assigneeName,'QA Agent');
    const transferred=await assignments.assign(session,chat,transferRequest.body);
    assert.equal(transferred.assigneeId,agent.user.id);
    assert.ok(new Date(transferred.updatedAt)>new Date(before.updatedAt));
    assert.ok((await assignments.listAssignments(session))[0].updatedAt);
    assert.equal((await service.notification(admin.token,session,chat)).allowed,false);
    assert.equal((await service.notification(agent.token,session,chat)).allowed,true);
    ok('transfer stores trusted target, preserves same-owner clock, changes notifications');
    const code=randomBytes(32).toString('base64url');
    const hash=createHash('sha256').update(code).digest('hex');
    await runner.query("INSERT INTO openwa.operator_recovery (user_id,token_hash,expires_at) VALUES ($1,$2,NOW()-INTERVAL '1 minute')",[agent.user.id,hash]);
    await assert.rejects(()=>service.resetPassword(agent.user.username,code,'new-test-password'),e=>e.getStatus()===401);ok('expired recovery code rejected');
    await runner.query("UPDATE openwa.operator_recovery SET expires_at=NOW()+INTERVAL '15 minutes' WHERE user_id=$1",[agent.user.id]);
    await assert.rejects(()=>service.resetPassword(agent.user.username,'invalid-code','new-test-password'),e=>e.getStatus()===401);ok('invalid recovery code rejected');
    await service.resetPassword(agent.user.username,code,'new-test-password');
    await assert.rejects(()=>service.me(agent.token),e=>e.getStatus()===401);
    await assert.rejects(()=>service.login(agent.user.username,'test-only-password'),e=>e.getStatus()===401);
    const recovered=await service.login(agent.user.username,'new-test-password');
    assert.equal(recovered.user.id,agent.user.id);agent.token=recovered.token;ok('password recovery replaces password and revokes old sessions');
    await assert.rejects(()=>service.resetPassword(agent.user.username,code,'another-test-password'),e=>e.getStatus()===401);ok('recovery code cannot be reused');
    await service.updateUser(admin.token,agent.user.id,{role:'agent',active:false,canSend:false,canAssign:false});
    await assert.rejects(()=>service.assignmentTarget(admin.token,agent.user.id),e=>e.getStatus()===403);
    await assert.rejects(()=>service.me(agent.token),e=>e.getStatus()===401);
    assert.equal((await service.administration(admin.token)).unassignedUserId,null);ok('deactivation revokes sessions and clears recipient');
    await runner.query('SAVEPOINT last_admin');
    await runner.query("UPDATE openwa.operator_users SET role='agent' WHERE id<>$1",[admin.user.id]);
    await assert.rejects(()=>service.updateUser(admin.token,admin.user.id,{role:'agent',active:true,canSend:true,canAssign:true}),e=>e.getStatus()===409);
    await runner.query('ROLLBACK TO SAVEPOINT last_admin');ok('last administrator protected');
    console.log(passed+' checks passed; no WhatsApp messages sent.');
  } finally {
    await runner.rollbackTransaction();await runner.release();await db.destroy();
    console.log('All temporary test changes rolled back.');
  }
}
main().catch(error=>{console.error(error.message);process.exitCode=1;});
